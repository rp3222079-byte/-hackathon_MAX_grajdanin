"""Ошибки приложения.

Роутеры не возвращают 404 и 409 вручную, а поднимают эти исключения:
их текст подставляется в ответ API как понятное жильцу сообщение,
а не как «Internal Server Error».
"""


class DomovoyError(Exception):
    """Базовая ошибка приложения: текст уходит жильцу в ответе."""


class NotFoundError(DomovoyError):
    """Запрошенной записи нет."""


class ConflictError(DomovoyError):
    """Запись уже существует: такой адрес у жильца уже заведён."""
